const GROUP_BY_EN = Object.fromEntries(GROUPS.map((g) => [g.en, g.id]));

export const ENTRIES: Entry[] = ROWS.map(([slug, ko, desc, kw = '']) => {
  const doc = API_DOCS[slug];
  return {name: doc.title, slug, ko, desc, group: GROUP_BY_EN[doc.group], kw};
});

export const BY_NAME: Record<string, Entry> = Object.fromEntries(ENTRIES.map((e) => [e.name, e]));

export function searchEntries(list: Entry[], query: string): Entry[] {
  const q = query.trim().toLowerCase();
  if (!q) return list;
  const words = q.split(/\s+/);
  return list.filter((e) => {
    const hay = `${e.name} ${e.slug} ${e.ko} ${e.desc} ${e.kw}`.toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}

export function docsUrl(e: Entry): string {
  return `https://ant.design/components/${e.slug}`;
}
